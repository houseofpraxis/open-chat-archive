def _chat_page(model: InspectionModel, session: SessionProjection) -> str:
    record = model.records[session.key]
    topology = session.topology
    labels = _component_labels(session.components, topology.derived_shape if topology else "unknown")
    components = "".join(_component_summary(label, component, session, topology) for label, component in zip(labels, session.components))
    literal = session.literal_relationship_keys or session.relationship_keys
    relations = "".join(_record_details(model, key) for key in literal)
    derived = {"declared_shape": topology.declared_shape if topology else None,
               "derived_shape": topology.derived_shape if topology else "unknown",
               "basis": topology.basis if topology else "incomplete_or_unknown",
               "roots": [key[0] for key in session.roots], "leaves": [key[0] for key in session.leaves],
               "components": len(session.components), "depth": session.depth,
               "active_node": session.active_node,
               "active_children": [key[0] for key in topology.active_children] if topology else []}
    continuation = ""
    if topology and topology.active_children:
        continuation = "<p class=\"continuation\">The source-selected active node has " + str(len(topology.active_children)) + \
            " continuation child" + ("ren" if len(topology.active_children) != 1 else "") + ": " + \
            ", ".join("<a href=\"#" + _message_anchor(key) + "\"><code>" + _h(key[0]) + "</code></a>" for key in topology.active_children) + ".</p>"
    source = _source_for_session(model, session)
    operator = "<p><strong>Source registry (operator metadata; NOT canonical evidence):</strong> raw scope <code>" + _h(source["source_scope_id"]) + "</code>; source ID " + _h(source.get("source_id") or "none") + "; status " + _h(source["registry_status"]) + "; label " + _h(source["display_label"] or "none") + "; account " + _h(source.get("account_identifier") or "none") + "; instance " + _h(source.get("instance_identifier") or "none") + "; category " + _h(source.get("category") or "none") + ".</p>"
    header = "<p><a href=\"../index.html\">Archive dashboard</a> · <a href=\"../sources.html\">Source scopes</a></p><h1>Chat projection</h1><p>Literal title: " + _h(record["body"].get("title", "Untitled")) + "</p>" + operator + \
        "<p class=\"meta\">Parent-child relationships are the only graph evidence. Source ordinal is a source coordinate, not time. " \
        "Timeline order uses source_ordinal only as a display sort. When sibling indexes are missing or duplicate, the graph uses a deterministic display-only source-ordinal/key fallback. All other relationships remain literal records.</p>" + _details("Canonical session body", record["body"]) + _details("Protected identity", record["identity"]) + \
        _details("Namespaced extensions", record.get("extensions", {})) + _details("Inspector-derived topology values", derived) + \
        continuation + "<h2>Parent-child graph</h2>" + _graph_tree(model, session) + "<h2>Components</h2><ol>" + components + "</ol><h2>Literal relationships</h2>" + relations + \
        "<h2>Source-ordinal timeline</h2><p class=\"meta\">Messages, events, spans, and turns in source_ordinal order. This is not chronology.</p>"
    timeline = "".join(_message_card(model, key) if model.records[key]["record_type"] == "message" else _record_details(model, key) for key in session.timeline_keys)
    shown = set(session.timeline_keys) | {session.key} | set(literal)
    other = [key for key in session.record_keys if key not in shown and model.records[key]["record_type"] != "observation"]
    observations = [key for key in session.record_keys if model.records[key]["record_type"] == "observation"]
    return header + timeline + "<h2>Other associated canonical records</h2>" + "".join(_record_details(model, key) for key in other) + \
        "<h2>Session-scoped observations</h2><p class=\"meta\">" + str(len(observations)) + " observation records are associated; message-local bindings are also on each message card.</p>"


def _component_summary(label: str, component: tuple[tuple[str, str], ...], session: SessionProjection,
                       topology: Any) -> str:
    """Render visible component facts; never require JSON or JavaScript to find them."""
    roots = [key for key in component if key in session.roots]
    root_links = ", ".join("<a href=\"#" + _message_anchor(key) + "\"><code>" + _h(key[0]) + "</code></a>"
                           for key in roots) or "none observed"
    message_links = ", ".join("<a href=\"#" + _message_anchor(key) + "\"><code>" + _h(key[0]) + "</code></a>"
                              for key in component)
    active = topology.active_node if topology else None
    active_marker = " <strong>Contains active node.</strong>" if active in {key[0] for key in component} else ""
    message_count = str(len(component)) + " message" + ("" if len(component) == 1 else "s")
    return "<li><strong>" + _h(label) + "</strong> — " + message_count + ". Root(s): " + \
        root_links + ". Messages: " + message_links + "." + active_marker + "</li>"


def _graph_tree(model: InspectionModel, session: SessionProjection) -> str:
    if not session.message_keys:
        return "<p>No messages.</p>"
    if session.topology and session.topology.basis == "revision_ambiguous":
        return "<p class=\"meta\">Graph rendering stopped: parent-child graph evidence has ambiguous revisions. " \
            "Each message revision remains available as its own timeline card; no arbitrary revision lookup was built.</p>"
    outgoing: dict[str, list[str]] = {}
    incoming: set[str] = set()
    lookup = {key[0]: key for key in session.message_keys}
    for key in session.relationship_keys:
        body = model.records[key]["body"]
        if body.get("from_id") not in lookup or body.get("to_id") not in lookup:
            continue
        outgoing.setdefault(body["from_id"], []).append(body["to_id"])
        incoming.add(body["to_id"])
    by_edge = {(model.records[key]["body"].get("from_id"), model.records[key]["body"].get("to_id")): model.records[key]["body"]
               for key in session.relationship_keys
               if model.records[key]["body"].get("from_id") in lookup and model.records[key]["body"].get("to_id") in lookup}
    fallback_parents: list[str] = []
    for parent, children in outgoing.items():
        sibling = [by_edge[(parent, child)].get("sibling_index") for child in children]
        if all(isinstance(index, int) for index in sibling) and len(sibling) == len(set(sibling)):
            children.sort(key=lambda entity_id: by_edge[(parent, entity_id)]["sibling_index"])
        else:
            children.sort(key=lambda entity_id: (model.records[lookup[entity_id]]["body"].get("source_ordinal", 10 ** 9), entity_id))
            fallback_parents.append(parent)
    def node(entity_id: str, seen: frozenset[str]) -> str:
        record = model.records[lookup[entity_id]]
        marker = " active-hint" if entity_id == session.active_node else ""
        label = _h(record["body"].get("role")) + " ordinal " + _h(record["body"].get("source_ordinal"))
        if entity_id in seen:
            return "<li class=\"cycle\">cycle <code>" + _h(entity_id) + "</code></li>"
        kids = outgoing.get(entity_id, [])
        branch = " class=\"branch\"" if len(kids) > 1 else ""
        nested = "<ul>" + "".join(node(child, seen | {entity_id}) for child in kids) + "</ul>" if kids else ""
        return "<li" + branch + "><span class=\"node" + marker + "\"><code>" + _h(entity_id) + "</code> " + label + "</span>" + nested + "</li>"
    roots = [key[0] for key in session.roots] or [key[0] for key in session.message_keys if key[0] not in incoming]
    if not roots: roots = sorted(lookup)
    ordering = ("<p class=\"meta\">Child ordering uses complete, distinct sibling_index values.</p>"
                if not fallback_parents else
                "<p class=\"meta\">Child ordering fallback (display-only) for parent(s) " +
                ", ".join("<code>" + _h(parent) + "</code>" for parent in sorted(fallback_parents)) +
                ": sibling_index is incomplete or not distinct, so children sort by source ordinal then canonical entity ID.</p>")
    return ordering + "<ul class=\"graph\">" + "".join(node(root, frozenset()) for root in roots) + "</ul>"


def _message_card(model: Any, key: tuple[str, str]) -> str:
    record = model.records[key]; body = record["body"]
    parts = []
    for part in body.get("content", []):
        kind = part.get("type", "unknown")
        if kind in {"text", "reasoning", "code"}: parts.append("<h3>Literal " + _h(kind) + " content</h3><pre class=\"literal\">" + _h(part.get("text", "")) + "</pre>")
        else: parts.append("<h3>Literal " + _h(kind) + " content part</h3>" + _details("Canonical content part", part))
    observations = [value for value in model.records.values() if value["record_type"] == "observation" and value["body"].get("subject") == {"entity_id": key[0], "revision_id": key[1]}]
    relationships = [
        value for value in model.records.values()
        if value["record_type"] == "relationship" and key[0] in {value["body"].get("from_id"), value["body"].get("to_id")}
    ]
    return "<article id=\"" + _message_anchor(key) + "\"><h2>Message <code>" + _h(key[0]) + "</code></h2><p>Role: <span class=\"label\">" + _h(body.get("role")) + "</span>; visibility: <span class=\"label\">" + _h(body.get("visibility")) + "</span>; source ordinal: <code>" + _h(body.get("source_ordinal")) + "</code></p>" + "".join(parts) + \
        _details("Canonical body", body) + _details("Protected identity", record["identity"]) + _details("Namespaced extensions", record.get("extensions", {})) + \
        _details("Inspector-derived values", {"occurrences": [item.__dict__ for item in model.occurrences[key]], "canonical_record_key": list(key)}) + _details("Explicit incoming and outgoing relationships", [item["body"] for item in relationships]) + _details("Observations and evidence bindings", [item["body"] for item in observations]) + _details("Raw canonical JSON", record) + "</article>"


def _record_details(model: InspectionModel, key: tuple[str, str]) -> str:
    record = model.records[key]
    return "<details><summary>" + _h(record["record_type"]) + " <code>" + _h(key[0]) + "</code></summary>" + _details("Canonical body", record["body"]) + _details("Protected identity", record["identity"]) + _details("Namespaced extensions", record.get("extensions", {})) + _details("Inspector-derived values", {"occurrences": [item.__dict__ for item in model.occurrences[key]], "associated_sessions": model.record_sessions.get(key, ())}) + _details("Raw canonical JSON", record) + "</details>"


def _records_page(model: InspectionModel) -> str:
    counts = Counter(record["record_type"] for record in model.records.values())
    rows = []
    for key in sorted(model.records):
        record = model.records[key]
        sessions = model.record_sessions.get(key, ())
        rows.append("<tr><td>" + _h(record["record_type"]) + "</td><td><code>" + _h(key[0]) +
                    "</code></td><td><code>" + _h(key[1]) + "</code></td><td>" + str(len(sessions)) +
                    "</td><td>" + str(len(model.occurrences[key])) + "</td></tr>")
    summary = "<p><a href=\"index.html\">Archive dashboard</a></p><h1>All canonical records</h1><p>Every loaded canonical record is rendered below with its complete body, protected identity, namespaced extensions, occurrences, and associated sessions. This includes unassociated and cross-session records and all observation payloads. Source and blob bytes are never copied.</p>" + _details("Record type summary", dict(sorted(counts.items())), open_=True)
    table = "<table><thead><tr><th>Type</th><th>Entity</th><th>Revision</th><th>Associated sessions</th><th>Occurrences</th></tr></thead><tbody>" + "".join(rows) + "</tbody></table>"
    return summary + table + "<h2>Complete canonical record details</h2>" + "".join(_record_details(model, key) for key in sorted(model.records))


def _coverage_page(model: InspectionModel) -> str:
    ledgers: list[dict[str, Any]] = []; profile_paths: list[str] = []; bindings: list[dict[str, Any]] = []
    for record in model.records.values():
        if record["record_type"] == "import_batch":
            profile_paths.extend(record["body"].get("profile_paths", [])); ledgers.extend(record["body"].get("coverage_ledger", []))
        if record["record_type"] == "observation": bindings.extend(record["body"].get("bindings", []))
    disposition = Counter(item.get("disposition", "unknown") for item in ledgers)
    return "<p><a href=\"index.html\">Archive dashboard</a></p><h1>Coverage and evidence</h1><p>Full ledgers are retained below, including large ledgers.</p>" + _details("Coverage disposition summary", dict(sorted(disposition.items())), open_=True) + _details("Profile paths", profile_paths) + _details("Coverage ledger", ledgers) + _details("Observation evidence bindings", bindings)


def _blocked_page(name: str, code: str) -> str:
    body = "<h1>Archive blocked</h1><p>Normative validation failed. No projection was attempted.</p><p>Stable validator code: <code>" + _h(code) + "</code></p>"
    return _page("Archive blocked", body, asset_prefix="assets/")


def _preflight_registry(source_registry: Path | None, output: Path) -> SourceRegistry | None:
    if source_registry is None:
        return None
    registry_path = source_registry.resolve(strict=False)
    if _overlaps(registry_path, output.resolve(strict=False)):
        raise ValueError("REFUSE_REGISTRY_OUTPUT_OVERLAP")
    return load_source_registry(source_registry)


def build_all(archives_parent: Path, output: Path, *, schema_root: Path | None = None,
              source_registry: Path | None = None) -> bool:
    """Build all immediate archive children; return false if any were blocked."""
    parent = archives_parent.resolve(strict=True)
    if not parent.is_dir(): raise ValueError("ARCHIVES_PARENT_NOT_DIRECTORY")
    registry = _preflight_registry(source_registry, output)
    staging = _prepare_destination(output, [parent])
    failures: list[tuple[str, str]] = []; successes: list[tuple[str, InspectionModel]] = []
    try:
        _copy_assets(staging)
        candidates = sorted(item for item in parent.iterdir() if item.is_dir())
        for archive in candidates:
            try:
                model = load_archive(archive, schema_root=schema_root, source_registry=registry)
                _render_archive(model, staging / archive.name); successes.append((archive.name, model))
            except ValidationError as error:
                code = stable_validation_code(error); failures.append((archive.name, code))
                blocked = staging / archive.name; _copy_assets(blocked); _write(blocked / "index.html", _blocked_page(archive.name, code))
        rows = "".join("<li><a href=\"" + _h(name) + "/index.html\">" + _h(name) + "</a> — passed</li>" for name, _ in successes)
        rows += "".join("<li><a href=\"" + _h(name) + "/index.html\">" + _h(name) + "</a> — blocked: <code>" + _h(code) + "</code></li>" for name, code in failures)
        _write(staging / "index.html", _page("Archive inspector batch", "<h1>Archive inspector batch</h1><p>Valid archive artifacts are independent. Blocked archives expose only a stable validator code.</p><ul>" + rows + "</ul>", asset_prefix="assets/"))
        _write(staging / MARKER, MARKER_TEXT)
        _lock_permissions(staging)
        _install_destination(staging, output)
    except Exception:
        if staging.exists(): shutil.rmtree(staging)
        raise
    return not failures


def build_one(archive_root: Path, output: Path, *, schema_root: Path | None = None,
              source_registry: Path | None = None) -> bool:
    archive = archive_root.resolve(strict=True)
    registry = _preflight_registry(source_registry, output)
    staging = _prepare_destination(output, [archive])
    try:
        model = load_archive(archive, schema_root=schema_root, source_registry=registry)
        _render_archive(model, staging)
        _write(staging / MARKER, MARKER_TEXT)
        _lock_permissions(staging); _install_destination(staging, output)
    except Exception:
        if staging.exists(): shutil.rmtree(staging)
        raise
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a local restricted-unclassified archive inspection site")
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("build", "build-all"):
        item = sub.add_parser(command)
        item.add_argument("input", type=Path)
        item.add_argument("--output", type=Path, required=True)
        item.add_argument("--source-registry", type=Path)
    args = parser.parse_args(argv)
    try:
        passed = (build_all(args.input, args.output, source_registry=args.source_registry)
                  if args.command == "build-all" else
                  build_one(args.input, args.output, source_registry=args.source_registry))
    except (OSError, RuntimeError, ValueError) as error:
        # Configuration errors deliberately contain no archive values.
        print("inspector failed: " + str(error).split(" ", 1)[0], file=sys.stderr)
        return 2
    except ValidationError as error:
        print("inspector failed: " + stable_validation_code(error), file=sys.stderr)
        return 1
    if not passed:
        print("inspector completed with blocked archives", file=sys.stderr)
        return 1
    print("inspector completed")
    return 0


if __name__ == "__main__": raise SystemExit(main())
