MARKER = ".open-chat-archive-inspector-output"
MARKER_TEXT = "Generated by open-chat-archive-inspect; safe to replace.\n"
WARNING = "restricted-unclassified: local sensitive derivative; do not share or publish"


def _alpha_label(index: int) -> str:
    result = ""; value = index + 1
    while value:
        value, remainder = divmod(value - 1, 26)
        result = chr(ord("A") + remainder) + result
    return result


def _component_labels(components: tuple[tuple[Any, ...], ...], shape: str) -> tuple[str, ...]:
    return tuple(("Thread " if shape == "forest" else "Component ") + _alpha_label(index)
                 for index, _ in enumerate(components))


def _message_anchor(key: tuple[str, str]) -> str:
    """Opaque digest based, unique across all entity/revision message cards."""
    return "message-" + key[0].removeprefix("sha256:") + "-" + key[1].removeprefix("sha256:")


def _h(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _plain(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {key: _plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(item) for item in value]
    return value


def _json(value: Any) -> str:
    return _h(json.dumps(_plain(value), ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False))


def _page(title: str, body: str, *, asset_prefix: str) -> str:
    return "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">" \
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">" \
        "<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'self'; script-src 'self'; img-src 'none'; media-src 'none'; connect-src 'none'; font-src 'none'; base-uri 'none'; form-action 'none'\">" \
        f"<title>{_h(title)}</title><link rel=\"stylesheet\" href=\"{_h(asset_prefix)}site.css\"></head>" \
        f"<body><p class=\"warning\">{WARNING}</p>{body}<script src=\"{_h(asset_prefix)}site.js\"></script></body></html>\n"


def _details(label: str, value: Any, *, open_: bool = False) -> str:
    return f"<details{' open' if open_ else ''}><summary>{_h(label)}</summary><pre>{_json(value)}</pre></details>"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    path.write_text(text, encoding="utf-8")
    os.chmod(path, 0o600)


def _copy_assets(root: Path) -> None:
    assets = root / "assets"; assets.mkdir(parents=True, exist_ok=True, mode=0o700)
    for name in ("site.css", "site.js"):
        target = assets / name
        target.write_text(resources.files("open_chat_archive.site_assets").joinpath(name).read_text(encoding="utf-8"), encoding="utf-8")
        os.chmod(target, 0o600)


def _lock_permissions(root: Path) -> None:
    for path in [root, *root.rglob("*")]:
        if path.is_symlink():
            raise RuntimeError("generated output unexpectedly contains symlink")
        os.chmod(path, 0o700 if path.is_dir() else 0o600)


def _overlaps(left: Path, right: Path) -> bool:
    try:
        left.relative_to(right); return True
    except ValueError:
        try: right.relative_to(left); return True
        except ValueError: return False


def _prepare_destination(output: Path, inputs: Iterable[Path]) -> Path:
    output = output.resolve(strict=False)
    if any(_overlaps(output, item.resolve(strict=False)) for item in inputs):
        raise ValueError("REFUSE_INPUT_OUTPUT_OVERLAP")
    if output.exists():
        marker = output / MARKER
        try:
            marker_is_regular = stat.S_ISREG(marker.lstat().st_mode)
            owned = output.is_dir() and marker_is_regular and marker.read_text(encoding="utf-8") == MARKER_TEXT
        except OSError:
            owned = False
        if not owned: raise ValueError("REFUSE_UNOWNED_OUTPUT")
    output.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    staging = output.parent / ("." + output.name + ".inspector-" + uuid.uuid4().hex)
    staging.mkdir(mode=0o700)
    return staging


def _install_destination(staging: Path, output: Path) -> None:
    output = output.resolve(strict=False)
    try:
        if output.exists(): shutil.rmtree(output)
        staging.replace(output)
    except Exception:
        if staging.exists(): shutil.rmtree(staging)
        raise


def _diagnostics(model: InspectionModel) -> str:
    if not model.diagnostics: return "<p>No exploratory findings or projection limitations.</p>"
    rows = "".join("<tr><td>" + _h(item.code) + "</td><td>" + _h(item.severity) + "</td><td>" +
                   _h(item.category) + "</td><td>" + _h(item.scope) + "</td><td>" +
                   "<br>".join(_h(value) for value in item.related_opaque_ids) + "</td><td>" +
                   _h(item.count) + "</td></tr>" for item in model.diagnostics)
    return "<table><thead><tr><th>Code</th><th>Severity</th><th>Class</th><th>Scope</th><th>Opaque IDs</th><th>Count</th></tr></thead><tbody>" + rows + "</tbody></table>"


def _render_archive(model: InspectionModel, root: Path) -> None:
    _copy_assets(root)
    report = model.report()
    _write(root / "inspection-report.json", json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    type_rows = "".join(f"<tr><td>{_h(kind)}</td><td>{count}</td></tr>" for kind, count in report["record_counts_by_type"].items())
    batches = "".join(f"<li>{_h(item['batch_id'])}: {_h(item['adapter']['namespace'])} {_h(item['adapter']['version'])}</li>" for item in report["batch_metadata"])
    aggregate = report["aggregate_metadata"]
    aggregate_details = "".join(_details(label.replace("_", " "), value) for label, value in aggregate.items())
    analysis_details = _details("Graph metrics", report["graph_metrics"]) + _details("Evidence-coordinate precision", report["evidence_metrics"]) + _details("Coverage metrics", report["coverage_metrics"])
    index = f"<h1>Archive inspector</h1><p>Normative validation: <span class=\"status\">passed</span>. " \
        "This status is a single validator outcome, not a claim that every internal rule passed independently.</p>" \
        f"<p>Archive: <code>{_h(model.archive_id)}</code>; adapters: {_h(', '.join(model.adapters))}; validator elapsed {report['validation'].get('elapsed_ms', 'n/a')} ms</p>" \
        f"<p><a href=\"sources.html\">Source scopes and operator metadata</a> · <a href=\"records.html\">All canonical records</a> · <a href=\"coverage.html\">Coverage and evidence</a> · <a href=\"inspection-report.json\">Machine-readable report</a></p>" \
        f"<h2>Batch metadata</h2><ul>{batches}</ul>" + _adapter_summary_table(report) + \
        f"<h2>Record types</h2><table><tr><th>Type</th><th>Unique records</th></tr>{type_rows}</table><h2>Aggregate debugging dashboard</h2>{aggregate_details}{analysis_details}" \
        "<h2>Chat catalog</h2><label>Filter catalog (progressive enhancement): <input data-catalog-filter></label>" + _chat_catalog(model) + \
        "<h2>Diagnostics</h2><p>Exploratory findings and projection limitations are non-normative.</p>" + _diagnostics(model)
    _write(root / "index.html", _page("Archive inspector", index, asset_prefix="assets/"))
    _write(root / "records.html", _page("Canonical records", _records_page(model), asset_prefix="assets/"))
    _write(root / "coverage.html", _page("Coverage and evidence", _coverage_page(model), asset_prefix="assets/"))
    _write(root / "sources.html", _page("Source scopes", _sources_page(report), asset_prefix="assets/"))
    for session in model.sessions:
        _write(root / "chats" / session.page_name, _page("Chat projection", _chat_page(model, session), asset_prefix="../assets/"))
    _lock_permissions(root)


def _adapter_summary_table(report: dict[str, Any]) -> str:
    summaries = report.get("adapter_summaries") or {}
    if not summaries:
        return ""
    rows = []
    for namespace, item in summaries.items():
        counts = item.get("diagnostic_counts") or {}
        detail = ", ".join(f"{code} {count}" for code, count in counts.items()) or "none"
        rows.append("<tr><td><code>" + _h(namespace) + "</code></td><td>" + _h(item.get("session_count")) +
                    "</td><td>" + _h(item.get("earliest_created_at") or "unknown") +
                    "</td><td>" + _h(item.get("latest_created_at") or "unknown") +
                    "</td><td>" + _h(item.get("diagnostic_total", 0)) + " / " + _h(item.get("affected_chat_count", 0)) +
                    "</td><td>" + _h(detail) + "</td></tr>")
    return "<h2>Per-adapter summary</h2><p>Chat counts and date ranges use each session's own adapter namespace, not the archive-level adapter list. Dates are canonical <code>created_at</code>/<code>updated_at</code> when present.</p>" \
        "<table><thead><tr><th>Adapter</th><th>Chats</th><th>Earliest</th><th>Latest</th><th>Occurrences / affected chats</th><th>Codes</th></tr></thead><tbody>" + \
        "".join(rows) + "</tbody></table>"


def _chat_catalog(model: InspectionModel) -> str:
    rows: list[str] = []
    for session in model.sessions:
        record = model.records[session.key]; body = record["body"]
        title = body.get("title", "Untitled")
        adapter = record.get("identity", {}).get("adapter_namespace", "unknown")
        created = body.get("created_at") or body.get("updated_at") or "unknown"
        topology = session.topology
        shape = topology.derived_shape if topology else "unknown"
        basis = topology.basis if topology else "incomplete_or_unknown"
        # Structural facts remain in the diagnostics table and report.  Hide
        # them from this row only when this session's topology independently
        # proves they are informational forest facts.
        confirmed_forest = shape == "forest" and basis == "complete_parent_child"
        structural_info = {"MULTIPLE_SESSION_ROOTS", "DISCONNECTED_SESSION_GRAPH"}
        findings = [item.code for item in model.diagnostics
                    if (session.key[0] in item.related_opaque_ids
                        or session.key[0] in item.associated_session_ids)
                    and not (confirmed_forest and item.severity == "info"
                             and item.code in structural_info)]
        label = "forest (" + str(len(session.components)) + " threads)" if shape == "forest" else shape
        finding_text = ", ".join(findings) or "none"
        if shape == "forest" and basis == "complete_parent_child":
            finding_text = ("confirmed forest topology" if finding_text == "none"
                            else "confirmed forest topology; " + finding_text)
        source = _source_for_session(model, session)
        source_text = "<code>" + _h(source["source_scope_id"]) + "</code><br>" + _h(source["registry_status"])
        if source["display_label"] is not None:
            source_text += ": " + _h(source["display_label"])
        rows.append("<tr data-catalog-row><td><a href=\"chats/" + _h(session.page_name) + "\">" + _h(title) + "</a></td><td><code>" +
                    _h(adapter) + "</code></td><td>" + source_text + "</td><td>" + _h(created) + "</td><td><code>" +
                    _h(session.key[0]) + "</code><br><code>" + _h(session.key[1]) + "</code></td><td>" + str(len(session.message_keys)) +
                    "</td><td>" + _h(label) + " (" + _h(basis) + ")<br>" + str(len(session.roots)) + "/" + str(len(session.leaves)) + "/" + str(len(session.components)) +
                    "</td><td>" + _h(finding_text) + "</td></tr>")
    return "<table><thead><tr><th>Literal title</th><th>Adapter</th><th>Raw scope; operator status</th><th>Created</th><th>Canonical IDs</th><th>Messages</th><th>Topology; roots/leaves/components</th><th>Session diagnostics</th></tr></thead><tbody>" + "".join(rows) + "</tbody></table>"


def _source_for_session(model: InspectionModel, session: SessionProjection) -> Mapping[str, Any]:
    identity = model.records[session.key].get("identity", {})
    archive_id = identity.get("archive_id")
    namespace = identity.get("adapter_namespace")
    scope = identity.get("source_scope_id", "unknown")
    registry = getattr(model, "source_registry", None)
    matched = (registry.resolve(archive_id, namespace, scope)
               if registry is not None and isinstance(archive_id, str)
               and isinstance(namespace, str) and isinstance(scope, str) else None)
    return {"source_scope_id": scope, "registry_status": matched.get("status") if matched else "unregistered",
            "source_id": matched.get("source_id") if matched else None,
            "display_label": matched.get("display_label") if matched else None,
            "account_identifier": matched.get("account_identifier") if matched else None,
            "instance_identifier": matched.get("instance_identifier") if matched else None,
            "category": matched.get("category") if matched else None}


