// Error is a fixed-code failure. Error() returns only the code.
type Error struct {
	Code string
	Exit int
}

func (e *Error) Error() string { return e.Code }

func errc(code string, exit int) *Error { return &Error{Code: code, Exit: exit} }

func ExitCode(err error) int {
	if err == nil {
		return 0
	}
	var e *Error
	if errors.As(err, &e) {
		return e.Exit
	}
	return 4
}

func ErrorCode(err error) string {
	if err == nil {
		return ""
	}
	var e *Error
	if errors.As(err, &e) {
		return e.Code
	}
	return OutputWrite
}
